# Variables de tipo texto
nombre = "helen"
print(type(nombre))

# Variables de tipo numerico (entero)
edad = 20
print(type(edad))

# Variables de tipo numerico (decimal)
calificacion = 7.5
print(type(calificacion))

# Variables de tipo bool (true/false)
estado_civil = False
print(type(estado_civil))

print(nombre, edad, calificacion, estado_civil)